def check_plan(plan: CoursePlan) -> list[str]:
    """The requirements this plan fails, as sentences. Empty means it holds.

    Two of these — unique slugs, prerequisites earlier-only — are also enforced by
    `CoursePlan`'s own validator, so a plan that came out of `model_validate`
    cannot fail them and those branches are unreachable on that path. They are
    restated because a plan does not always come from there: one rebuilt
    field-by-field from stored `course_modules` rows goes through
    `model_construct`, which runs no validator at all, and that is the shape the
    revise handler compares against. The checks that exist ONLY here are the
    pedagogical ones — a plan can be perfectly well-formed and still be useless.
    `tests/test_courses_core.py` drives every branch through `model_construct` so
    each has been seen to fail.
    """
    failures: list[str] = []
    modules = list(plan.modules)
    if not modules:
        failures.append("A course needs at least one module.")
        return failures
    if len(modules) > MAX_COURSE_MODULES:
        failures.append(f"A course may have at most {MAX_COURSE_MODULES} modules.")

    seen: set[str] = set()
    for module in modules:
        if module.slug in seen:
            failures.append(f"Module slug {module.slug!r} appears twice; every slug must differ.")
        for prerequisite in module.prerequisites:
            if prerequisite not in seen:
                failures.append(
                    f"Module {module.slug!r} lists prerequisite {prerequisite!r}, which is not "
                    "an EARLIER module. A prerequisite may only name a module before it."
                )
        seen.add(module.slug)

    for module in modules:
        if not module.brief.strip():
            failures.append(
                f"Module {module.slug!r} has an empty brief. Every module's brief must be "
                "self-contained: it is handed to the notebook generator on its own."
            )
        if not module.objectives:
            failures.append(
                f"Module {module.slug!r} has no objectives. State at least one thing the "
                "reader can do after this module."
            )
        if not isinstance(module.kind, NotebookKind):
            failures.append(f"Module {module.slug!r} has an unknown kind {module.kind!r}.")

    total = sum(module.duration_minutes or 0 for module in modules)
    cap = MAX_MODULE_MINUTES * MAX_COURSE_MODULES
    if total > cap:
        failures.append(
            f"The course totals {total} minutes, past the {cap}-minute ceiling. "
            "Shorten modules or drop one."
        )
    return failures


