def _module_readme(module: PlannedModule, *, seq: int) -> str:
    lines = [f"# Module {seq}: {module.title}", ""]
    if module.topic:
        lines += [module.topic, ""]
    if module.objectives:
        lines += ["## What you will be able to do", ""]
        lines += [f"- {item}" for item in module.objectives]
        lines += [""]
    if module.key_concepts:
        lines += ["## Key concepts", ""]
        lines += [f"- {item}" for item in module.key_concepts]
        lines += [""]
    if module.deliverable:
        lines += ["## Deliverable", "", module.deliverable, ""]
    if module.prerequisites:
        lines += [
            "## Before this module",
            "",
            "Finish: " + ", ".join(f"`{slug}`" for slug in module.prerequisites),
            "",
        ]
    if module.duration_minutes:
        lines += [f"_About {module.duration_minutes} minutes._", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def _course_readme(plan: CoursePlan, *, framework: Framework | None = None) -> str:
    """The top-level README, in the shape of the Quanmatic study-group README:
    what it is, who it is for, a Week/Topic/Key concepts/Deliverable table, and a
    quick start with `uv`."""
    fw = framework or Framework()
    rows = []
    for index, module in enumerate(plan.modules, start=1):
        concepts = ", ".join(module.key_concepts) or "—"
        rows.append(
            f"| {index} | [{module.title}]({module.slug}/) | {module.topic or '—'} | "
            f"{concepts} | {module.deliverable or '—'} |"
        )
    lines = [
        f"# {plan.title}",
        "",
        plan.summary or "",
        "",
        "## Who this is for",
        "",
        "Anyone working through the modules in order. Each module is one notebook you run",
        "and edit; each assumes only what the modules before it established.",
        "",
        "## The plan",
        "",
        "| # | Module | Topic | Key concepts | Deliverable |",
        "| --- | --- | --- | --- | --- |",
        *rows,
        "",
        "## Quick start",
        "",
        "```bash",
        "uv sync",
        "uv run jupyter lab",
        "```",
        "",
        f"Notebooks run against {fw.name} `{fw.version}` on Python 3.11 or newer.",
        "Open a module's directory and run its notebook top to bottom.",
        "",
        "---",
        "",
        "Built by Nala, Leona Quantum's teaching assistant.",
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


def _curriculum_yaml(plan: CoursePlan, slug: str, *, framework: Framework | None = None) -> str:
    fw = framework or Framework()
    data = {
        "slug": slug,
        "title": plan.title,
        "description": plan.summary,
        "framework": fw.name,
        "framework_version": fw.version,
        "units": [
            {
                "id": module.slug,
                "directory": module.slug,
                "title": module.title,
                "topic": module.topic,
                "key_concepts": list(module.key_concepts),
                "deliverable": module.deliverable,
                "order": index,
            }
            for index, module in enumerate(plan.modules, start=1)
        ],
    }
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=88)


def course_to_curriculum_sources(
    course_plan: CoursePlan,
    notebook_specs: dict[str, NotebookSpec],
    *,
    slug: str = "course",
    framework: Framework | None = None,
) -> dict[Path, str]:
    """The source tree `build_curriculum` expects, keyed by relative path.

    One directory per module, each with a `README.md` written from the module's own
    topic/concepts/objectives/deliverable and a `<kind>.nb.py` rendered from the
    notebook that module generated. A module with no generated notebook is skipped:
    `build_curriculum` compiles sources, and there is nothing honest to compile from
    a module that was only ever planned.
    """
    files: dict[Path, str] = {
        Path("README.md"): _course_readme(course_plan, framework=framework),
        Path("curriculum.yaml"): _curriculum_yaml(course_plan, slug, framework=framework),
    }
    for index, module in enumerate(course_plan.modules, start=1):
        spec = notebook_specs.get(module.slug)
        if spec is None:
            continue
        directory = Path(module.slug)
        files[directory / "README.md"] = _module_readme(module, seq=index)
        files[directory / module_filename(module.kind)] = render_source(spec)
    return files


def export_course_zip(
    course_plan: CoursePlan,
    notebook_specs: dict[str, NotebookSpec],
    *,
    slug: str = "course",
    framework: Framework | None = None,
) -> bytes:
    """Build the course through `build_curriculum` (never executing) and zip it.

    The zip is what the reader downloads: the compiled `.ipynb` files, the READMEs
    and the `curriculum.yaml`, laid out exactly as `build_curriculum` writes them.
    Nothing is executed here — the notebooks were already executed in the sandbox
    when their versions were generated, and `execute=True` would want a kernel this
    process is not entitled to start.
    """
    with tempfile.TemporaryDirectory(prefix="leona-course-") as tmp:
        source_root = Path(tmp) / "src"
        out_root = Path(tmp) / "out"
        for relative, text in course_to_curriculum_sources(
            course_plan, notebook_specs, slug=slug, framework=framework
        ).items():
            target = source_root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        manifest = build_curriculum(source_root, out_root, execute=False)
        # `build_curriculum` deliberately does NOT copy `curriculum.yaml` into the
        # build — for the hand-authored Quanmatic curriculum it is the build's input,
        # not part of the deliverable. A downloaded course is different: the yaml IS
        # the reader's table of contents and the thing that lets them rebuild the
        # course themselves, so it is written across explicitly rather than by
        # loosening the builder for both callers.
        (out_root / "curriculum.yaml").write_text(
            (source_root / "curriculum.yaml").read_text(encoding="utf-8"), encoding="utf-8"
        )
        # A builder that compiled nothing must not be zipped into a plausible-looking
        # archive of READMEs. Structure failures do NOT stop the export (the notebooks
        # already ran; `manifest.failures()` is advice, not a gate) — an empty build is
        # a different thing, and it is the one that would ship silently.
        if not manifest.notebooks or not any(nb.outputs for nb in manifest.notebooks):
            raise RuntimeError("course export produced no notebooks")
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(out_root.rglob("*")):
                if path.is_file():
                    archive.write(path, arcname=path.relative_to(out_root).as_posix())
        return buffer.getvalue()


