"""A course: many notebooks as one plan, from one prompt.

`curriculum.py` builds a repository from `.nb.py` sources somebody authored. This
module is the other half — it turns a **generated** `CoursePlan` into exactly the
source tree `build_curriculum` expects, so the product's own courses and the
hand-authored Quanmatic curriculum go through one builder rather than two.

What lives here:

- `plan_prompt` / `revise_plan_prompt` — what the planner model is told. The
  framework facts are IMPORTED from `prompts.py`, never restated: a second copy is a
  second thing to get wrong, and a wrong framework fact ships a failing cell to every
  reader.
- `check_plan` — the failable checks on a returned plan, as readable sentences the
  worker can hand straight back to the model on its one retry.
- `course_to_curriculum_sources` / `export_course_zip` — the plan plus its generated
  notebooks, rendered as a curriculum source tree and zipped through
  `build_curriculum`.
- `COURSE_STARTERS` — starting points the composer offers before the reader types.

The one thing a module's `brief` must do, and the reason it is repeated in three
places below: a module is generated by `notebook.generate` ALONE, with no sight of
its siblings. Everything the notebook needs to know about what came before has to be
inside its own brief.
"""

