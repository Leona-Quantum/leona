#: One `.nb.py` file per module, named for the module's kind. Kinds outside this map
#: are authored as a lesson file — the kind still rides in the source's YAML header,
#: so `build_curriculum` compiles the right builds either way; only the filename is
#: normalised.
_FILENAME_FOR_KIND: dict[NotebookKind, str] = {
    NotebookKind.LAB: "lab",
    NotebookKind.LESSON: "lesson",
    NotebookKind.CHALLENGE: "challenge",
    NotebookKind.QUIZ: "quiz",
    NotebookKind.DEMO: "demo",
    NotebookKind.WALKTHROUGH: "walkthrough",
    NotebookKind.HARDWARE: "hardware",
    NotebookKind.BENCHMARK: "benchmark",
    NotebookKind.PROJECT: "project",
}


def module_filename(kind: NotebookKind) -> str:
    """The `.nb.py` filename a module of this kind is authored as."""
    return f"{_FILENAME_FOR_KIND.get(kind, 'lesson')}.nb.py"


