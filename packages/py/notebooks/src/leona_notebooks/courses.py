PLAN_SYSTEM_PROMPT = """\
You are Nala, Leona Quantum's teaching assistant. You plan whole COURSES: an ordered
sequence of Jupyter notebooks that takes one reader from where they are to what they
asked to be able to do. Return JSON only — one `CoursePlan` object, nothing else.

What a good plan is:
1. Ordered by dependency, not by topic tidiness. Module N may assume only what modules
   1..N-1 established, and says so in `prerequisites`.
2. Each module is ONE sitting: a single notebook a reader finishes in the time given.
   If an idea does not fit in one, split it across two modules rather than compressing it.
3. Each module ends with something that runs — a `deliverable` the reader can point at.
4. The reader's own preferences (level, analogies, maths, language, framework, how long,
   which topics) are requirements. Honour them; where you cannot, say so in the summary.
5. Later modules revisit earlier ones deliberately: the plan should say, in a module's
   brief, what the reader already built that this module extends.

The `brief` field is the load-bearing one. Each module's brief is handed ON ITS OWN to
a notebook generator that cannot see the other modules and has never read this plan. So
every brief must be self-contained: what to teach, for whom, at what level, what the
reader ALREADY established in the earlier modules (name them and what they built), what
this notebook must end with, and anything to avoid because a later module owns it. Write
it as an instruction to the generator, not as a description of the module.

Never invent a citation. Never plan a module that needs credentials, the network, or
more than about 60 seconds of CPU per notebook — a hardware module ships credential-free
cells the reader runs where their own account lives.
"""


REVISE_PLAN_SYSTEM_PROMPT = """\
You are Nala, editing a course plan with its reader in a chat. You are given the current
plan and the reader's message. Return JSON only, with three keys:

  {"reply": "<what you say to the reader>",
   "summary": "<one line naming the change>",
   "plan": <a complete CoursePlan object>}

Return the WHOLE plan every time, not a patch — plans are small. The rules that make the
rewrite safe:

- **Keep the slug of every module the reader did not ask you to change, byte-identical.**
  A module whose slug survives keeps the notebook already generated for it; a module
  whose slug changes is treated as a new module and loses that work. Never renumber or
  re-slug modules just because their position moved.
- Give a genuinely new module a new slug that does not collide with any existing one.
- Keep `prerequisites` pointing only at modules that come EARLIER in the returned order.
- Keep every brief self-contained, and update the briefs of any modules whose earlier
  context changed because of this edit.
- If the request would break the course (a module that now depends on one you removed),
  say so in `reply` and make the nearest sound change you can.
- If the message is a question rather than an edit, answer it in `reply` and return the
  current plan unchanged.
"""


def _plan_json_schema() -> str:
    return json.dumps(CoursePlan.model_json_schema(), ensure_ascii=False)


def _framework_facts(framework: Framework | None) -> str:
    """The verified framework-facts block, imported from `prompts.py` rather than
    restated. `prompts` imports nothing from this module, so there is no cycle."""
    from leona_notebooks.prompts import FRAMEWORK_FACTS

    name = (framework or Framework()).name
    return FRAMEWORK_FACTS.get(name, "")


def _kinds_text() -> str:
    from leona_notebooks.templates import KIND_DESCRIPTIONS

    return "\n".join(f"- {kind.value}: {text}" for kind, text in KIND_DESCRIPTIONS.items())


def plan_prompt(
    *,
    brief: str,
    audience: Audience | None = None,
    style: Style | None = None,
    framework: Framework | None = None,
    module_count: int | None = None,
    response_locale: str = "en",
    seed_material: str = "",
) -> tuple[str, str]:
    """`(system, user)` for the course-planning call.

    `module_count` of `None` leaves the length to the planner within the cap; a
    number asks for exactly that many, which is what a reader who typed "an
    eight-week course" means.
    """
    length = (
        f"Plan EXACTLY {module_count} modules."
        if module_count is not None
        else (
            "Choose the number of modules the brief actually needs — as few as 2, never "
            f"more than {MAX_COURSE_MODULES}. A short ask gets a short course."
        )
    )
    payload = {
        "brief": brief,
        "audience": (audience or Audience()).model_dump(),
        "style": (style or Style()).model_dump(),
        "framework": (framework or Framework()).model_dump(),
        "response_language": response_locale,
        "module_count": module_count,
    }
    user = "\n\n".join(
        part
        for part in [
            "READER'S BRIEF (their own words):\n" + brief,
            "READER'S PREFERENCES (JSON):\n" + json.dumps(payload, ensure_ascii=False, indent=2),
            (
                "SEED MATERIAL (verbatim — cite it, never invent beyond it):\n" + seed_material
                if seed_material
                else ""
            ),
            "LENGTH:\n" + length,
            "NOTEBOOK KINDS you may give a module:\n" + _kinds_text(),
            "FRAMEWORK FACTS (a module must be plannable against these):\n"
            + _framework_facts(framework),
            (
                "OUTPUT: one JSON object matching this schema and nothing else.\n"
                "COURSE PLAN JSON SCHEMA:\n" + _plan_json_schema()
            ),
            (
                "Every module's `slug` is lowercase letters, digits and hyphens "
                "(e.g. `week-01-circuits`). Each `duration_minutes` is between 1 and "
                f"{MAX_MODULE_MINUTES}. Write `title`, `summary`, `topic`, `objectives`, "
                "`deliverable` and every `brief` in "
                f"{'Japanese (です・ます体)' if response_locale == 'ja' else 'English'}."
            ),
        ]
        if part
    )
    return PLAN_SYSTEM_PROMPT, user


def revise_plan_prompt(
    current_plan: CoursePlan,
    message: str,
    *,
    response_locale: str = "en",
    framework: Framework | None = None,
) -> tuple[str, str]:
    """`(system, user)` for a chat revision of the plan (not of any notebook)."""
    generated = [m.slug for m in current_plan.modules]
    user = "\n\n".join(
        [
            "CURRENT PLAN (JSON):\n" + current_plan.model_dump_json(indent=2),
            "MODULE SLUGS IN THE CURRENT PLAN (keep these unless asked to change them):\n"
            + ", ".join(generated),
            "READER'S MESSAGE:\n" + message,
            "FRAMEWORK FACTS:\n" + _framework_facts(framework),
            "COURSE PLAN JSON SCHEMA (the `plan` key):\n" + _plan_json_schema(),
            f"Reply language: {'Japanese' if response_locale == 'ja' else 'English'}.",
        ]
    )
    return REVISE_PLAN_SYSTEM_PROMPT, user


