#!/usr/bin/env node
// Emit RUNTIME tuples for every string enum in the contract.
//
// ## Why this exists when schema.d.ts already has the types
//
// `openapi-typescript` gives us `components["schemas"]["Framework"]` as a union
// type, and a union type cannot be iterated, searched, or rendered. So every
// place that needs the VALUES restates them by hand, and #262 is the record of
// what that costs: adding three frameworks meant editing the contracts enum,
// openapi.json, ToolName, the worker event set, the framework→tool map, the DB
// constraint, and two separate TypeScript registries — and nothing failed when
// one of them was missed. A hand-copied list is silent when it is wrong.
//
// The generated file is a `.ts`, not a `.d.ts`, because that is the whole point:
// `as const` tuples must survive to runtime. `openapi-typescript --enum-values`
// looks like the answer and is not — it emits values into an ambient context,
// where TS1039 refuses an initializer.
//
// ## Every string enum, not a curated list
//
// The obvious design is a list of the schemas worth emitting. That list is a
// third place to forget something, with exactly the failure mode this file
// exists to remove — you add an enum, you do not add it to the list, and the
// generator silently does not generate it. Emitting all of them costs a few
// unused tuples and nothing else.
//
// ## How it is gated
//
// It is chained into `pnpm --filter @majorana/contracts-gen gen`, which ci.yml
// already runs followed by `git diff --exit-code packages/ts/contracts-gen`. So
// a contract change that is not regenerated fails CI with no new wiring — the
// same rule that has kept schema.d.ts current since ADR-0008.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(repoRoot, "packages/py/contracts/openapi.json");
const TARGET = join(repoRoot, "packages/ts/contracts-gen/src/enums.ts");

const spec = JSON.parse(readFileSync(SOURCE, "utf8"));
const schemas = spec?.components?.schemas;
if (!schemas || typeof schemas !== "object") {
  // Fail closed. An unreadable spec that produced an empty file would delete
  // every registry downstream and read as "the contract has no enums".
  console.error("generate-contract-enums: openapi.json has no components.schemas");
  process.exit(1);
}

/** Pure string enums only — anything with a shape is not a value list. */
function stringEnumValues(schema) {
  if (!schema || typeof schema !== "object") return null;
  if (schema.type !== "string" || !Array.isArray(schema.enum)) return null;
  if (schema.enum.length === 0) return null;
  if (!schema.enum.every((value) => typeof value === "string")) return null;
  return schema.enum;
}

const emitted = [];
for (const name of Object.keys(schemas).sort()) {
  const values = stringEnumValues(schemas[name]);
  if (values) emitted.push([name, values]);
}

if (emitted.length === 0) {
  console.error("generate-contract-enums: found no string enums — refusing to write an empty file");
  process.exit(1);
}

/** `Framework` -> `FRAMEWORK_VALUES`, `QpuRunStatus` -> `QPU_RUN_STATUS_VALUES`. */
function constantName(schemaName) {
  return `${schemaName
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .toUpperCase()}_VALUES`;
}

const header = `// GENERATED by scripts/generate-contract-enums.mjs — do not hand-edit.
//
// Runtime companions to the union types in schema.d.ts, which cannot be
// iterated. Regenerate with:
//
//   uv run python -m majorana_contracts.export
//   pnpm --filter @majorana/contracts-gen gen
//
// ci.yml runs that and then \`git diff --exit-code packages/ts/contracts-gen\`,
// so a stale copy of this file cannot merge.
//
// Each tuple is \`as const\`, so it is assignable to the matching
// \`components["schemas"][...]\` union and a consumer gets a compile error rather
// than a silently-wider type. ORDER IS THE CONTRACT'S ORDER — it is what the
// Python enum declares, so anything user-visible should sort or label rather
// than rely on it.
`;

const body = emitted
  .map(([name, values]) => {
    const members = values.map((value) => `  ${JSON.stringify(value)},`).join("\n");
    return `/** ${name} — ${values.length} member${values.length === 1 ? "" : "s"}. */\nexport const ${constantName(name)} = [\n${members}\n] as const;`;
  })
  .join("\n\n");

writeFileSync(TARGET, `${header}\n${body}\n`);
console.log(
  `generate-contract-enums: wrote ${emitted.length} enums to packages/ts/contracts-gen/src/enums.ts`,
);
